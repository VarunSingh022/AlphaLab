"""The v4.0 historical inventory: every deferral, non-goal and open item since v2.0.0, classified.

The pre-v4 audit (v3.10) inventoried ROADMAP's boundaries and its optional
list; v3.13 added the "Known limitations" and "DEFERRED" lists of ADR-0042 to
ADR-0044 (TST-015). Neither read the v2-era ADRs' "Explicit non-goals", "Not in
scope" and "Consequences of deferring" sections, nor the CHANGELOG's "Known
gaps", "Known Limitations", "Not in scope", "Deferred, unchanged", "Recorded"
and "Still open" sections, nor ``nowandfuture.md``'s open questions. The v4.0
archaeology did (ledger TST-017), and two of those items hid live defects:
ADR-0029's "no live-object parameter persistence" (PER-008) and the
non-resumable replay ADR-0029 and ADR-0030 deferred, which nothing had tracked
since (FUT-001).

This script is the classification. :data:`CLASSIFICATION` holds, for each
source section, one row per item -- matched by the item's opening words -- with
its status, the ledger entries or code that are its evidence, and a note. The
ledger entry for each section (``HIS-xxx``) is written from it, and so is
``docs/audit/V4_HISTORICAL_INVENTORY.md``.

    python docs/audit/scripts/historical_inventory_v4.py --write   # ledger block + document
    python docs/audit/scripts/historical_inventory_v4.py --check   # fails if either is stale

``tests/regression/test_every_adr_deferral_is_classified.py`` reads the ADRs and
the CHANGELOG through :func:`stated_items` and holds every item to exactly one
row, and the generated files to this script.
"""

