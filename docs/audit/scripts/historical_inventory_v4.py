def _normalize(text: str) -> str:
    return " ".join(re.sub(r"\*\*|`", "", text).split())


def _changelog_section(version: str, heading: str) -> str:
    text = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    release = text.split(f"\n# [{version}]", 1)[1].split("\n# [", 1)[0]
    body = release.split(f"\n## {heading}\n", 1)[1]
    return re.split(r"\n#{1,2} |\n---", body, maxsplit=1)[0]


def _markdown_section(path: str, heading: str) -> str:
    text = (ROOT / path).read_text(encoding="utf-8")
    match = re.search(rf"^(#+) {re.escape(heading)}\s*$", text, re.M)
    if match is None:
        raise LookupError(f"{path} has no section {heading!r}")
    level = len(match.group(1))
    rest = text[match.end() :]
    end = re.search(rf"^#{{1,{level}}} |^---$", rest, re.M)
    return rest[: end.start()] if end else rest


def _section_text(section: Section) -> str:
    if section.path.startswith("CHANGELOG.md#"):
        return _changelog_section(section.path.split("#", 1)[1], section.heading)
    return _markdown_section(section.path, section.heading)


def stated_items() -> dict[str, list[str]]:
    """Every item each section states, normalized, keyed by its ledger entry."""

    found: dict[str, list[str]] = {}
    for section in SECTIONS:
        body = _section_text(section).strip()
        if section.shape == "bullets":
            items = re.findall(r"^[-*] (.+?)(?=\n[-*] |\n\n|\Z)", body, re.M | re.S)
        elif section.shape == "semicolons":
            paragraph = body.split("\n\n", 1)[0]
            items = [part for part in re.split(r";\s+", paragraph) if part.strip()]
        else:
            items = [body]
        found[section.ledger_id] = [_normalize(item) for item in items]
    return found


def matches() -> dict[str, list[tuple[str, Row | None, int]]]:
    """Each stated item, the one row that classifies it (or ``None``), and how many rows matched."""

    out: dict[str, list[tuple[str, Row | None, int]]] = {}
    for ledger_id, items in stated_items().items():
        rows = CLASSIFICATION.get(ledger_id, ())
        listed: list[tuple[str, Row | None, int]] = []
        for item in items:
            hits = [row for row in rows if item.startswith(row[0])]
            listed.append((item, hits[0] if len(hits) == 1 else None, len(hits)))
        out[ledger_id] = listed
    return out


def problems() -> list[str]:
    """Every item no single row classifies, every row no item uses, every unknown status."""

    found: list[str] = []
    for ledger_id, listed in matches().items():
        used: set[str] = set()
        for item, row, count in listed:
            if row is None:
                found.append(f"{ledger_id}: {count} rows match {item[:80]!r}")
            else:
                used.add(row[0])
        for row in CLASSIFICATION.get(ledger_id, ()):
            if row[0] not in used:
                found.append(f"{ledger_id}: row {row[0]!r} classifies nothing stated")
            if row[1] not in STATUSES:
                found.append(f"{ledger_id}: unknown status {row[1]!r}")
    for ledger_id in set(CLASSIFICATION) - {section.ledger_id for section in SECTIONS}:
        found.append(f"{ledger_id}: classification for no section")
    return found


def _yaml(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


