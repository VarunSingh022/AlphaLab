"""A release's artifacts are held to the commit they were built from (plan WS-29, RQ).

v4.2.1's verification record named the artifacts' hashes and the host, and
nothing else: which commit they came from, and whether that commit alone could
produce them, were left to the preflight's artifact name. Since v4.3
``release_preflight.py distributions`` names the commit and its tree in the
record, holds every file in the wheel's ``alphalab/`` and every source file in
the sdist to the commit's bytes, and rebuilds both artifacts from ``git archive``
of the commit in a fresh directory, which must give the same bytes.

The tests run on small git repositories made here, so they need git and the
``[dev]`` build tools and nothing else -- and no network: the rebuild runs
without build isolation.
"""

from __future__ import annotations

import hashlib
import importlib.util
import io
import os
import subprocess
import sys
import tarfile
import zipfile
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parents[2]
VERSION = "9.9.9"
PYPROJECT = f"""[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[project]
name = "alphalab"
version = "{VERSION}"
requires-python = ">=3.12"

[tool.hatch.build.targets.wheel]
packages = ["alphalab"]
"""


@pytest.fixture(scope="module")
def script() -> ModuleType:
    path = ROOT / "docs" / "audit" / "scripts" / "release_preflight.py"
    spec = importlib.util.spec_from_file_location("release_preflight_correspondence", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _git(repository: Path, *arguments: str) -> str:
    done = subprocess.run(
        ["git", *arguments],
        cwd=repository,
        capture_output=True,
        text=True,
        check=True,
        env={
            **os.environ,
            "GIT_AUTHOR_NAME": "t",
            "GIT_AUTHOR_EMAIL": "t@example.invalid",
            "GIT_COMMITTER_NAME": "t",
            "GIT_COMMITTER_EMAIL": "t@example.invalid",
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_CONFIG_SYSTEM": os.devnull,
        },
    )
    return done.stdout.strip()


def _project(root: Path, files: dict[str, bytes]) -> str:
    """A repository holding ``files``, committed; returns the commit."""

    root.mkdir()
    for path, data in files.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_bytes(data)
    _git(root, "init", "-q")
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", "release")
    return _git(root, "rev-parse", "HEAD")


FILES = {
    "pyproject.toml": PYPROJECT.encode(),
    "alphalab/__init__.py": b'__version__ = "9.9.9"\n',
    "alphalab/core/__init__.py": b"",
    "alphalab/py.typed": b"",
    "data/binary.bin": bytes(range(256)),
    "LICENSE": b"MIT\n",
}


def test_the_commit_and_its_files_are_read_from_the_object_store(
    script: ModuleType, tmp_path: Path
) -> None:
    repository = tmp_path / "repo"
    commit = _project(repository, FILES)
    (repository / "alphalab" / "__init__.py").write_bytes(b"edited, never committed\n")

    assert script.commit_identity(repository) == (
        commit,
        _git(repository, "rev-parse", "HEAD^{tree}"),
    )
    assert script.commit_files(commit, repository) == FILES
    assert script.commit_identity(tmp_path) is None


def _artifacts(folder: Path, wheel_files: dict[str, bytes], sdist_files: dict[str, bytes]) -> None:
    folder.mkdir()
    with zipfile.ZipFile(folder / f"alphalab-{VERSION}-py3-none-any.whl", "w") as wheel:
        for name, data in wheel_files.items():
            wheel.writestr(name, data)
        wheel.writestr(f"alphalab-{VERSION}.dist-info/METADATA", b"Name: alphalab\n")
    with tarfile.open(folder / f"alphalab-{VERSION}.tar.gz", "w:gz") as sdist:
        for name, data in {**sdist_files, "PKG-INFO": b"generated by the build\n"}.items():
            member = tarfile.TarInfo(f"alphalab-{VERSION}/{name}")
            member.size = len(data)
            sdist.addfile(member, io.BytesIO(data))


PACKAGE = {path: data for path, data in FILES.items() if path.startswith("alphalab/")}
SOURCE = {path: data for path, data in FILES.items() if path != "data/binary.bin"}


def test_artifacts_holding_the_commits_files_correspond(script: ModuleType, tmp_path: Path) -> None:
    _artifacts(tmp_path / "dist", PACKAGE, SOURCE)

    problems, lines = script.correspondence_problems(tmp_path / "dist", VERSION, FILES)

    assert problems == []
    assert lines == [
        "wheel: 3 package files, each the commit's, none missing",
        "sdist: 5 source files, each the commit's",
    ]


@pytest.mark.parametrize(
    ("wheel", "sdist", "found"),
    [
        ({**PACKAGE, "alphalab/__init__.py": b"tampered"}, SOURCE, "differ from the commit"),
        ({**PACKAGE, "alphalab/extra.py": b""}, SOURCE, "are not in the commit"),
        (
            {k: v for k, v in PACKAGE.items() if k != "alphalab/py.typed"},
            SOURCE,
            "the commit's but not in the wheel",
        ),
        (PACKAGE, {**SOURCE, "LICENSE": b"edited"}, "LICENSE is not the commit's"),
        (PACKAGE, {**SOURCE, "setup.py": b""}, "setup.py is not the commit's"),
    ],
    ids=["changed", "added", "left out", "sdist changed", "sdist added"],
)
def test_an_artifact_that_differs_from_its_commit_is_refused(
    script: ModuleType, tmp_path: Path, wheel: dict[str, bytes], sdist: dict[str, bytes], found: str
) -> None:
    _artifacts(tmp_path / "dist", wheel, sdist)

    problems, _ = script.correspondence_problems(tmp_path / "dist", VERSION, FILES)

    assert any(found in problem for problem in problems), problems


def _built(repository: Path) -> Path:
    dist = repository / "dist"
    subprocess.run(
        [sys.executable, "-m", "build", "--no-isolation", "--outdir", str(dist), str(repository)],
        cwd=repository,
        capture_output=True,
        check=True,
    )
    return dist


def test_artifacts_rebuild_from_the_commit_alone_to_the_same_bytes(
    script: ModuleType, tmp_path: Path
) -> None:
    repository = tmp_path / "repo"
    commit = _project(repository, FILES)
    dist = _built(repository)

    problems, lines = script.reproduction_problems(
        dist, VERSION, commit, sys.executable, root=repository, isolation=False
    )
    assert problems == []
    assert lines == ["rebuilt from the commit alone: both artifacts byte-identical"]

    wheel = dist / f"alphalab-{VERSION}-py3-none-any.whl"
    wheel.write_bytes(wheel.read_bytes() + b"\0")
    problems, _ = script.reproduction_problems(
        dist, VERSION, commit, sys.executable, root=repository, isolation=False
    )
    assert problems == [f"{wheel.name} rebuilt from {commit[:12]} is not byte-identical"]


def test_the_record_names_the_commit_and_tree(script: ModuleType, tmp_path: Path) -> None:
    dist = tmp_path / "dist"
    _artifacts(dist, PACKAGE, SOURCE)
    script.write_checksums(dist, VERSION)
    record = tmp_path / "VERIFICATION.txt"

    script._record(record, VERSION, dist, ["a check"], [], ("c" * 40, "t" * 40))

    text = record.read_text(encoding="utf-8")
    assert f"Built from commit {'c' * 40}, tree {'t' * 40}." in text
    assert hashlib.sha256((dist / f"alphalab-{VERSION}.tar.gz").read_bytes()).hexdigest() in text


@pytest.mark.parametrize(
    ("commit", "refusal"),
    [
        ("0" * 40, "{commit!r} is not a commit {root} can resolve"),
        # The command line's default, outside a checkout: an unpacked sdist, a scratch copy.
        ("HEAD", "{root} is not a git checkout: name the commit the artifacts were built from "
         "with --commit"),
    ],
    ids=["unknown commit", "no checkout"],
)  # fmt: skip
def test_artifacts_whose_commit_cannot_be_resolved_are_refused_before_installing(
    script: ModuleType, tmp_path: Path, commit: str, refusal: str
) -> None:
    dist = tmp_path / "dist"
    _artifacts(dist, PACKAGE, SOURCE)
    (dist / f"alphalab-{VERSION}-py3-none-any.whl").unlink()
    with zipfile.ZipFile(dist / f"alphalab-{VERSION}-py3-none-any.whl", "w") as wheel:
        for name, data in PACKAGE.items():
            wheel.writestr(name, data)
        wheel.writestr(
            f"alphalab-{VERSION}.dist-info/METADATA",
            f"Metadata-Version: 2.4\nName: alphalab\nVersion: {VERSION}\n",
        )
        wheel.writestr(f"alphalab-{VERSION}.dist-info/licenses/LICENSE", "MIT")

    problems = script.distributions(
        dist, VERSION, None, sys.executable, commit=commit, root=tmp_path
    )

    assert problems[-1] == refusal.format(commit=commit, root=tmp_path)


def test_outside_a_checkout_a_missing_dist_is_still_refused_by_name(
    script: ModuleType, tmp_path: Path
) -> None:
    """The paths are checked before the source is resolved (the v4.1 rule).

    Until this was fixed, ``distributions dist`` run outside a checkout said only
    that there was no checkout; the scratch copies of the v4.3 mutation run found
    it, where ``test_release_paths``'s missing-directory test failed.
    """

    with pytest.raises(script.PathRefused, match=r"the distribution directory .* does not exist"):
        script.distributions(
            tmp_path / "dist", VERSION, None, sys.executable, commit="HEAD", root=tmp_path
        )


def test_no_workflow_checks_artifacts_without_their_source() -> None:
    """``--no-source`` is for assets checked away from their source; no gate may use it."""

    workflows = sorted((ROOT / ".github" / "workflows").glob("*.yml"))

    assert workflows
    for workflow in workflows:
        assert "--no-source" not in workflow.read_text(encoding="utf-8"), workflow.name


def test_the_distributions_check_holds_and_rebuilds_from_the_commit_it_names(
    script: ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The command wires both checks in, and the record and verdict carry what they found.

    The checks themselves are tested above; this holds ``distributions`` to running
    them on the resolved commit -- the v4.3 mutation run found nothing in the suite
    noticed when the rebuild was never called (its N04). The rebuild and the
    installs are replaced here by recorders, so nothing is built or installed.
    """

    repository = tmp_path / "repo"
    commit = _project(repository, FILES)
    dist = tmp_path / "dist"
    _artifacts(dist, PACKAGE, SOURCE)
    rebuilt: list[tuple[Any, ...]] = []

    def rebuild(*arguments: Any, **keywords: Any) -> tuple[list[str], list[str]]:
        rebuilt.append((*arguments, keywords))
        return ["the rebuild differed"], ["rebuilt from the commit alone: recorded"]

    monkeypatch.setattr(script, "reproduction_problems", rebuild)
    monkeypatch.setattr(script, "archive_problems", lambda dist, version: [])
    monkeypatch.setattr(
        script, "install_and_smoke", lambda artifact, *rest: ([], [f"{artifact.name}: smoked"])
    )
    record = tmp_path / "VERIFICATION.txt"

    problems = script.distributions(
        dist, VERSION, record, sys.executable, commit="HEAD", root=repository
    )

    assert rebuilt == [(dist, VERSION, commit, sys.executable, {"root": repository})]
    assert problems == ["the rebuild differed"]
    text = record.read_text(encoding="utf-8")
    assert f"- source: commit {commit}, tree " in text
    assert "- wheel: 3 package files, each the commit's, none missing" in text
    assert "- rebuilt from the commit alone: recorded" in text
    assert text.startswith(f"AlphaLab {VERSION} -- distribution verification: FAILED")
